verify_database() {
  local database_path="$1"
  [[ -f "${database_path}" ]] || fail "数据库文件不存在：${database_path}"
  run_as_app "${PYTHON_BIN}" -c '
import hashlib
import json
import sqlite3
import sys
from pathlib import Path

path = Path(sys.argv[1]).resolve()
with sqlite3.connect(f"{path.as_uri()}?mode=ro", uri=True) as db:
    result = db.execute("PRAGMA integrity_check").fetchone()
    tables = {
        row[0]
        for row in db.execute("SELECT name FROM sqlite_master WHERE type = '\''table'\''")
    }
    revision_row = (
        db.execute("SELECT version_num FROM alembic_version LIMIT 1").fetchone()
        if "alembic_version" in tables
        else None
    )
if not result or result[0] != "ok":
    raise SystemExit(f"integrity_check failed: {result}")

manifest_path = path.with_name(path.name + ".manifest.json")
manifest_state = "not present (integrity only)"
if manifest_path.is_file():
    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    hasher = hashlib.sha256()
    with path.open("rb") as source:
        for chunk in iter(lambda: source.read(1024 * 1024), b""):
            hasher.update(chunk)
    if manifest.get("databaseFile") != path.name:
        raise SystemExit("manifest databaseFile does not match")
    if manifest.get("sha256") != hasher.hexdigest():
        raise SystemExit("manifest SHA-256 does not match")
    if manifest.get("sizeBytes") != path.stat().st_size:
        raise SystemExit("manifest size does not match")
    manifest_state = "verified"
revision = revision_row[0] if revision_row else "none (empty or pre-migration DB)"
print(
    f"database integrity: ok; manifest: {manifest_state}; "
    f"schema revision: {revision}; file: {path}"
)
' "${database_path}"
}

secure_database_permissions() {
  local database_path="$1"
  "${PYTHON_BIN}" - "${DATA_DIR}" "${database_path}" \
    "$(id -u "${APP_USER}")" "$(id -g "${APP_USER}")" <<'PY'
import os
import stat
import sys

data_root, database_path, uid_text, gid_text = sys.argv[1:]
parent, filename = os.path.split(database_path)
if parent != data_root or not filename or "/" in filename:
    raise SystemExit("database must be a direct child of the data directory")

directory_flags = os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW
file_flags = os.O_RDONLY | os.O_NOFOLLOW
directory_fd = os.open(data_root, directory_flags)
try:
    database_fd = os.open(filename, file_flags, dir_fd=directory_fd)
    try:
        if not stat.S_ISREG(os.fstat(database_fd).st_mode):
            raise SystemExit("database target is not a regular file")
        os.fchown(database_fd, int(uid_text), int(gid_text))
        os.fchmod(database_fd, 0o600)
    finally:
        os.close(database_fd)
finally:
    os.close(directory_fd)
PY
}

rewrite_database_url() {
  local new_url="$1"
  local temporary_env
  temporary_env="$(mktemp "${ENV_FILE%/*}/app.env.XXXXXX")"
  awk -v replacement="MVP_DATABASE_URL=${new_url}" '
    BEGIN { replaced = 0 }
    /^MVP_DATABASE_URL=/ {
      print replacement
      replaced = 1
      next
    }
    { print }
    END {
      if (!replaced) {
        print replacement
      }
    }
  ' "${ENV_FILE}" >"${temporary_env}"
  install -m 0640 -o root -g "${APP_GROUP}" "${temporary_env}" "${ENV_FILE}.next"
  mv -f -- "${ENV_FILE}.next" "${ENV_FILE}"
  rm -f -- "${temporary_env}"
}

active_database_url() {
  sed -n 's/^MVP_DATABASE_URL=//p' "${ENV_FILE}" | tail -n1
}

