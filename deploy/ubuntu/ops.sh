acquire_lock() {
  workspace_stage "等待运维锁" "有其他备份或部署任务运行时请等待其结束，不要删除锁文件。" E_LOCK
  exec 9>>"${LOCK_FILE}"
  flock --wait 300 9 || fail "等待 300 秒仍未取得运维锁：${LOCK_FILE}；另一项部署或备份可能仍在运行。" E_LOCK
}

health_check() {
  local attempts="${1:-1}"
  local delay_seconds="${2:-0}"
  local attempt
  for ((attempt = 1; attempt <= attempts; attempt += 1)); do
    if curl --fail --silent --show-error --connect-timeout 3 --max-time 10 \
      "http://127.0.0.1:${BACKEND_PORT}/api/v1/health/ready" >/dev/null \
      && curl --fail --silent --show-error --connect-timeout 3 --max-time 10 \
        "http://127.0.0.1:${FRONTEND_PORT}/" >/dev/null; then
      printf 'health: ok (backend :%s, frontend :%s)\n' \
        "${BACKEND_PORT}" "${FRONTEND_PORT}"
      return 0
    fi
    if ((attempt < attempts)); then
      sleep "${delay_seconds}"
    fi
  done
  printf '健康检查未通过：后端 http://127.0.0.1:%s/api/v1/health/ready；前端 http://127.0.0.1:%s/\n请执行 sudo solution-workspace status 和 sudo solution-workspace logs。\n' "${BACKEND_PORT}" "${FRONTEND_PORT}" >&2
  return 1
}

