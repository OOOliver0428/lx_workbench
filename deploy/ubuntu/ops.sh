stop_for_maintenance() {
  local stopped=true unit state previous_backend previous_frontend
  if [[ "${MAINTENANCE_STARTED}" == false ]]; then
    previous_backend="$(systemctl show --property=ActiveState --value solution-workspace-backend.service)" || return 1
    previous_frontend="$(systemctl show --property=ActiveState --value solution-workspace-frontend.service)" || return 1
    PREVIOUS_TIMER_STATE="$(systemctl show --property=ActiveState --value solution-workspace-backup.timer)" || return 1
    if [[ "${previous_backend}" == active && "${previous_frontend}" == active ]]; then
      PREVIOUS_APP_STATE=running
    elif [[ "${previous_backend}" =~ ^(inactive|failed)$ && "${previous_frontend}" =~ ^(inactive|failed)$ ]]; then
      PREVIOUS_APP_STATE=stopped
    fi
  fi
  MAINTENANCE_STARTED=true
  WORKSPACE_STATE="已进入维护阶段，服务可能部分停止。"
  systemctl stop solution-workspace-backup.timer || stopped=false
  systemctl stop solution-workspace-backup.service || stopped=false
  systemctl stop solution-workspace.target || stopped=false
  systemctl stop solution-workspace-backend.service solution-workspace-frontend.service || stopped=false
  for unit in solution-workspace-backup.timer solution-workspace-backup.service \
    solution-workspace-backend.service solution-workspace-frontend.service; do
    state="$(systemctl show --property=ActiveState --value "${unit}")" || stopped=false
    [[ "${state}" == inactive || "${state}" == failed ]] || stopped=false
  done
  [[ "${stopped}" == true ]] || return 1
  WORKSPACE_STATE="应用和备份定时器已停止。"
}

restore_previous_services() {
  case "${PREVIOUS_APP_STATE}" in
    running)
      systemctl start solution-workspace.target || return 1
      health_check 3 1 || return 1
      ;;
    stopped) ;;
    *) return 1 ;;
  esac
  if [[ "${PREVIOUS_TIMER_STATE}" == active ]]; then
    systemctl start solution-workspace-backup.timer || return 1
    systemctl is-active --quiet solution-workspace-backup.timer || return 1
  fi
}

clone_sqlite_database() {
  local source_path="$1"
  local target_path="$2"
  run_as_app "${PYTHON_BIN}" -c '
import sqlite3
import sys
from contextlib import closing
from pathlib import Path

source_path, target_path = sys.argv[1:3]
with (
    closing(sqlite3.connect(f"{Path(source_path).as_uri()}?mode=ro", uri=True)) as source,
    closing(sqlite3.connect(target_path)) as target,
):
    source.backup(target)
    target.commit()
' "${source_path}" "${target_path}"
}

checkpoint_database() {
  local database_path="$1"
  run_as_app "${PYTHON_BIN}" -c '
import sqlite3
import sys

with sqlite3.connect(sys.argv[1]) as db:
    checkpoint = db.execute("PRAGMA wal_checkpoint(TRUNCATE)").fetchone()
    if checkpoint and checkpoint[0] != 0:
        raise SystemExit("数据库仍有事务占用，无法完成 WAL 检查点；未移动数据库文件")
    result = db.execute("PRAGMA integrity_check").fetchone()
    if not result or result[0] != "ok":
        raise SystemExit(f"integrity_check failed: {result}")
' "${database_path}"
}

move_database_bundle() {
  local source_path="$1"
  local target_path="$2"
  local suffix
  [[ -f "${source_path}" ]] || return 1
  mv -- "${source_path}" "${target_path}" || return 1
  for suffix in -wal -shm; do
    if [[ -e "${source_path}${suffix}" ]]; then
      mv -- "${source_path}${suffix}" "${target_path}${suffix}" || return 1
    fi
  done
}

SWITCH_ACTIVE="false"
SWITCH_ENV_SNAPSHOT=""
SWITCH_TARGET=""
SWITCH_PRESERVED_TARGET=""
SWITCH_CANDIDATE=""
SWITCH_TIMESTAMP=""
SWITCH_SWAPPED="false"
SWITCH_FILES_UNCERTAIN=false

rollback_switch() {
  local reason="$1"
  local restored=true
  trap - ERR
  set +e
  if ! stop_for_maintenance; then
    WORKSPACE_STATE="切库恢复中止：无法确认服务全部停止；未继续移动数据库或配置。"
    WORKSPACE_ADVICE="先执行 status 和 logs；确认服务停止后，按回滚快照及 app.env.before 恢复。"
    SWITCH_ACTIVE=false
    return 1
  fi
  if [[ "${SWITCH_FILES_UNCERTAIN}" == true ]]; then
    WORKSPACE_STATE="数据库文件移动未完整结束，应用已停止；未尝试覆盖文件或自动恢复。"
    WORKSPACE_ADVICE="保留候选库、目标库及 ${SWITCH_ENV_SNAPSHOT}，核对完整文件组后按迁机/恢复手册处理。"
    SWITCH_ACTIVE=false
    return 1
  fi
  if [[ "${SWITCH_SWAPPED}" == "true" && -f "${SWITCH_TARGET}" ]]; then
    move_database_bundle \
      "${SWITCH_TARGET}" \
      "${SWITCH_TARGET}.failed-${SWITCH_TIMESTAMP}" || restored=false
  fi
  if [[ "${restored}" == true && -n "${SWITCH_PRESERVED_TARGET}" && -f "${SWITCH_PRESERVED_TARGET}" ]]; then
    move_database_bundle "${SWITCH_PRESERVED_TARGET}" "${SWITCH_TARGET}" || restored=false
  fi
  if [[ "${restored}" == true && -n "${SWITCH_CANDIDATE}" && -f "${SWITCH_CANDIDATE}" ]]; then
    move_database_bundle "${SWITCH_CANDIDATE}" "${SWITCH_CANDIDATE}.failed" || restored=false
  fi
  if [[ -f "${SWITCH_ENV_SNAPSHOT}" ]]; then
    if ! install -m 0640 -o root -g "${APP_GROUP}" "${SWITCH_ENV_SNAPSHOT}" "${ENV_FILE}.restore" \
      || ! mv -f -- "${ENV_FILE}.restore" "${ENV_FILE}"; then
      restored=false
    fi
  else
    restored=false
  fi
  if [[ "${restored}" == true ]] && restore_previous_services; then
    if [[ "${PREVIOUS_APP_STATE}" == running ]]; then
      WORKSPACE_STATE="切库失败，原数据库及配置已恢复，原服务通过健康检查。"
    else
      WORKSPACE_STATE="切库失败，原数据库及配置已恢复；应用保持操作前的停止状态。"
    fi
    MAINTENANCE_STARTED=false
  else
    stop_for_maintenance || true
    WORKSPACE_STATE="切库失败，恢复未完成；已尝试停服，请执行 status 确认，勿重复切库。"
    WORKSPACE_ADVICE="检查日志与 ${SWITCH_ENV_SNAPSHOT}，按部署手册恢复；不要删除失败候选库。"
  fi
  SWITCH_ACTIVE="false"
  printf '切库恢复处理：%s\n' "${reason}" >&2
}

switch_error_trap() {
  local status="$1"
  WORKSPACE_ERROR="切库过程中命令失败或操作被中断。"
  exit "${status}"
}

switch_database() {
  local mode="$1"
  local requested_path="$2"
  local target_path data_root current_path rollback_dir rollback_db source_path new_url

  [[ "${requested_path}" == /* ]] || fail "数据库路径必须是以 / 开头的绝对路径。"
  [[ ! -L "${requested_path}" ]] || fail "目标数据库不能是符号链接。" E_DATABASE
  [[ "${requested_path}" != *[[:space:]]* ]] || fail "数据库路径不能包含空格或换行。"
  [[ "${requested_path}" != *"'"* ]] || fail "数据库路径不能包含单引号。"
  target_path="$(realpath --canonicalize-missing -- "${requested_path}")"
  data_root="$(realpath -- "${DATA_DIR}")"
  [[ "$(dirname -- "${target_path}")" == "${data_root}" ]] || {
    fail "数据库必须直接放在 ${data_root} 根层，不能位于嵌套目录。"
  }
  [[ "${target_path}" == *.db ]] || fail "数据库文件名必须以 .db 结尾。"
  acquire_lock
  workspace_stage "校验数据库切换条件" "目标数据库须位于数据目录根层；检查路径、权限和备份校验清单。" E_DATABASE
  current_path="$(active_database_path)"
  [[ "${target_path}" != "${current_path}" ]] || fail "目标数据库已经在使用，无需切换。"

  workspace_stage "停服并备份当前数据库" "确认服务已停止并检查备份目录空间；失败时会尝试恢复未变更的服务。" E_BACKUP
  stop_for_maintenance
  [[ ! -L "${requested_path}" ]] || restart_unchanged_and_fail "维护期间目标数据库变成了符号链接。"
  target_path="$(realpath --canonicalize-missing -- "${requested_path}")"
  data_root="$(realpath -- "${DATA_DIR}")"
  [[ "$(dirname -- "${target_path}")" == "${data_root}" \
    && "${target_path}" == *.db ]] || {
    restart_unchanged_and_fail "进入维护后数据库路径发生变化，已取消切换。"
  }
  [[ "${target_path}" != "${current_path}" ]] || {
    restart_unchanged_and_fail "目标路径指向了当前数据库，已取消切换。"
  }
  if [[ "${mode}" == "switch" && -f "${target_path}" ]]; then
    [[ ! -L "${target_path}" ]] || {
      restart_unchanged_and_fail "目标数据库是符号链接，已取消切换。"
    }
    if ! secure_database_permissions "${target_path}" \
      || ! verify_database "${target_path}"; then
      restart_unchanged_and_fail "目标数据库校验失败；请检查完整性、配套清单和文件权限。"
    fi
  elif [[ "${mode}" == "promote" && -e "${target_path}" ]]; then
    restart_unchanged_and_fail "promote-db 目标文件已存在；请使用新的文件名，避免覆盖已有数据库。"
  fi

  if ! rollback_dir="$(new_operation_dir switches)"; then
    fail "无法创建切库回滚目录，请检查备份目录权限和空间。"
  fi
  if ! create_backup "${rollback_dir}"; then
    fail "停服备份失败，尚未切换数据库。"
  fi
  if ! rollback_db="$(backup_file_in "${rollback_dir}")"; then
    fail "找不到切库回滚快照，尚未切换数据库。"
  fi
  RECOVERY_SNAPSHOT="${rollback_db}"
  SWITCH_ENV_SNAPSHOT="${rollback_dir}/app.env.before"
  if ! install -m 0640 -o root -g "${APP_GROUP}" \
    "${ENV_FILE}" "${SWITCH_ENV_SNAPSHOT}"; then
    fail "无法备份运行配置，尚未切换数据库。"
  fi
  SWITCH_TIMESTAMP="$(date -u +%Y%m%dT%H%M%S%NZ)"
  SWITCH_TARGET="${target_path}"
  SWITCH_CANDIDATE="${DATA_DIR}/.switch-candidate-${SWITCH_TIMESTAMP}.db"
  SWITCH_PRESERVED_TARGET=""
  SWITCH_SWAPPED="false"
  SWITCH_ACTIVE="true"
  trap 'switch_error_trap 130' INT
  trap 'switch_error_trap 143' TERM

  if [[ "${mode}" == "promote" ]]; then
    source_path="${rollback_db}"
  elif [[ -f "${target_path}" ]]; then
    checkpoint_database "${target_path}"
    source_path="${target_path}"
  else
    source_path=""
  fi
  if [[ -n "${source_path}" ]]; then
    clone_sqlite_database "${source_path}" "${SWITCH_CANDIDATE}"
  fi

  new_url="sqlite:///${SWITCH_CANDIDATE}"
  DATA_MAY_HAVE_CHANGED=true
  workspace_stage "迁移候选数据库" "候选库迁移失败会尝试恢复原配置；请保留回滚快照。" E_MIGRATION
  rewrite_database_url "${new_url}"
  if ! workspace_run run_app_env "${ALEMBIC_BIN}" upgrade head; then
    fail "候选数据库迁移失败。"
  fi
  checkpoint_database "${SWITCH_CANDIDATE}"

  if [[ -f "${target_path}" ]]; then
    SWITCH_PRESERVED_TARGET="${target_path}.pre-switch-${SWITCH_TIMESTAMP}"
    SWITCH_FILES_UNCERTAIN=true
    move_database_bundle "${target_path}" "${SWITCH_PRESERVED_TARGET}"
    SWITCH_FILES_UNCERTAIN=false
  fi
  SWITCH_FILES_UNCERTAIN=true
  move_database_bundle "${SWITCH_CANDIDATE}" "${target_path}"
  SWITCH_SWAPPED="true"
  SWITCH_FILES_UNCERTAIN=false
  secure_database_permissions "${target_path}"
  rewrite_database_url "sqlite:///${target_path}"

  if ! systemctl start solution-workspace.target || ! health_check 12 2; then
    fail "切换后服务启动或健康检查失败。"
  fi
  systemctl start solution-workspace-backup.timer
  systemctl is-active --quiet solution-workspace-backup.timer
  SWITCH_ACTIVE="false"
  MAINTENANCE_STARTED=false
  trap - ERR INT TERM
  printf 'database switch completed: %s\n' "${target_path}"
  printf 'offline rollback snapshot: %s\n' "${rollback_db}"
  if [[ -n "${SWITCH_PRESERVED_TARGET}" ]]; then
    printf 'pre-migration target preserved: %s\n' "${SWITCH_PRESERVED_TARGET}"
  fi
}

prepare_offline_bundle() {
  local input="$1" checksum="${1}.sha256" checksum_line expected actual refs ref _commit
  [[ -f "${input}" && ! -L "${input}" && -r "${input}" ]] || {
    fail "找不到可读的普通 bundle 文件：${input}；请确认上传路径，不能使用目录或符号链接。" E_BUNDLE_FILE
  }
  [[ -f "${checksum}" && ! -L "${checksum}" && -r "${checksum}" ]] || {
    fail "缺少配套校验文件：${checksum}；请上传与 bundle 同一批生成的 .sha256 文件。" E_CHECKSUM_FILE
  }
  local releases=/var/lib/solution-workspace-releases
  [[ ! -L "${releases}" ]] || fail "发布暂存目录不能是符号链接：${releases}" E_BUNDLE_FILE
  install -d -m 0700 -o root -g root "${releases}"
  workspace_require_space "${releases}" "$(( $(stat -c '%s' -- "${input}") + 10485760 ))"
  offline_stage="$(mktemp -d "${releases}/update.XXXXXXXX")"
  install -m 0600 -o root -g root -- "${input}" "${offline_stage}/release.bundle"
  install -m 0600 -o root -g root -- "${checksum}" "${offline_stage}/release.sha256"
  # Parse exactly one digest, never execute the file or pass its paths to sha256sum.
  checksum_line="$(cat "${offline_stage}/release.sha256")"
  checksum_line="${checksum_line%$'\r'}"
  [[ "${checksum_line}" =~ ^([[:xdigit:]]{64})[[:blank:]]+\*?(.+)$ \
    && "${BASH_REMATCH[2]}" == "$(basename -- "${input}")" ]] || {
    fail "校验文件格式或文件名不匹配；请重新上传同一批生成的 bundle 和 .sha256，不要混用不同版本。" E_CHECKSUM_FORMAT
  }
  expected="${BASH_REMATCH[1],,}"
  actual="$(sha256sum "${offline_stage}/release.bundle")"
  actual="${actual%% *}"
  [[ "${actual}" == "${expected}" ]] || {
    fail "安装包 SHA-256 不一致，可能上传不完整；请重新上传两个配套文件。" E_CHECKSUM_MISMATCH
  }
  workspace_run git -C "${PROJECT_DIR}" bundle verify "${offline_stage}/release.bundle" || {
    fail "bundle 验证失败：包可能损坏，或服务器缺少增量包所需的历史提交。缺少基线时请使用 -FullHistory 重新打包。" E_BUNDLE_VERIFY
  }
  refs="$(git bundle list-heads "${offline_stage}/release.bundle")" || fail "无法读取 bundle 分支。" E_BUNDLE_VERIFY
  local -a heads=()
  while read -r _commit ref; do
    [[ "${ref}" == refs/heads/* ]] && heads+=("${ref#refs/heads/}")
  done <<<"${refs}"
  if [[ -z "${branch}" ]]; then
    [[ "${#heads[@]}" -eq 1 ]] || fail "包内有 ${#heads[@]} 个分支，无法自动选择；请使用 --branch 分支名指定目标。" E_BUNDLE_BRANCH
    branch="${heads[0]}"
  fi
  expected_commit="$(awk -v ref="refs/heads/${branch}" '$2 == ref {print $1}' <<<"${refs}")"
  [[ "${expected_commit}" =~ ^[[:xdigit:]]{40,64}$ ]] || fail "bundle 中不存在分支 ${branch}；请核对打包分支或 --branch 参数。" E_BUNDLE_BRANCH
  remote="${offline_stage}/release.bundle"
  printf '更新包校验通过；目标分支：%s；目标提交：%s\n' "${branch}" "${expected_commit}"
}

read_database_revision() {
  local database_path
  database_path="$(active_database_path)" || return 1
  # Alembic current loads the application engine, which can create a missing
  # database and change its journal mode. Diagnostics must only read the file.
  run_as_app "${PYTHON_BIN}" -c '
import sqlite3
import sys
from contextlib import closing
from pathlib import Path

path = Path(sys.argv[1])
try:
    with closing(sqlite3.connect(f"{path.as_uri()}?mode=ro", uri=True)) as db:
        revisions = [row[0] for row in db.execute("SELECT version_num FROM alembic_version")]
    if not revisions:
        raise ValueError("数据库没有迁移版本记录")
except (OSError, sqlite3.Error, ValueError) as error:
    print(f"数据库版本读取失败：{path}；{error}。请核对原数据库路径、权限和迁移记录，未创建或迁移数据库。", file=sys.stderr)
    raise SystemExit(1) from None
print(f"数据位置：{path}")
print("数据库版本：" + ", ".join(revisions))
' "${database_path}"
}

doctor() {
  local failures=0 project_status
  workspace_stage "只读检查部署状态" "按下方问题逐项检查；数据库不存在时请恢复正确路径或备份，勿重新生成密钥。" E_DOCTOR
  printf '部署检查（只读，不输出配置密钥）\n'
  git -C "${PROJECT_DIR}" log -1 --format='代码版本：%h %s' || failures=$((failures + 1))
  if ! project_status="$(git --no-optional-locks -C "${PROJECT_DIR}" status --porcelain)"; then
    printf '需处理：无法读取代码目录的 Git 状态，请检查路径和权限。\n'; failures=$((failures + 1))
  elif [[ -n "${project_status}" ]]; then
    printf '需处理：代码目录存在本地修改，更新前必须妥善保存。\n'; failures=$((failures + 1))
  fi
  read_database_revision || failures=$((failures + 1))
  health_check || failures=$((failures + 1))
  systemctl is-active --quiet solution-workspace-backup.timer || {
    printf '需处理：自动备份定时器未运行。\n'; failures=$((failures + 1))
  }
  systemctl is-enabled --quiet solution-workspace-backup.timer || {
    printf '需处理：自动备份定时器未设为开机启用。\n'; failures=$((failures + 1))
  }
  df -h -- "${PROJECT_DIR}" "${DATA_DIR}" "${BACKUP_DIR}" || failures=$((failures + 1))
  printf '迁机需单独转移：经过校验的数据库及 manifest、app.env（含原加密密钥）、对应版本代码；操作步骤见部署手册。\n'
  ((failures == 0)) || fail "发现 ${failures} 项待处理问题，请按上方提示逐项检查。" E_DOCTOR
}

