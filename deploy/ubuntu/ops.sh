workspace_on_failure() {
  if [[ -n "${old_commit:-}" ]]; then
    printf '更新前提交：%s\n目标提交：%s\n前端恢复目录：%s\n前端切换状态：%s\n' \
      "${old_commit}" "${new_commit:-未知}" "${frontend_stage_dir:-未创建}" \
      "${frontend_runtime_swapped:-未开始}" | workspace_error_details
  fi
  if [[ "${SWITCH_ACTIVE:-false}" == true ]]; then
    rollback_switch "切库命令失败或被中断"
  elif [[ "${MAINTENANCE_STARTED}" == true ]]; then
    if [[ "${DATA_MAY_HAVE_CHANGED}" == false ]]; then
      if [[ "${PREVIOUS_APP_STATE}" == stopped ]]; then
        WORKSPACE_STATE="代码和数据库未更新；应用在操作前已停止，本次保持停止。"
        restore_previous_services || WORKSPACE_STATE="代码和数据库未更新，应用保持原来的停止状态；备份定时器恢复失败。"
      elif [[ "${PREVIOUS_APP_STATE}" != running ]]; then
        WORKSPACE_STATE="代码和数据库未更新；操作前服务并非全部正常运行，未自动启动，请执行 status 检查。"
      elif restore_previous_services; then
        WORKSPACE_STATE="代码和数据库未更新；原服务及备份定时器已恢复并通过健康检查。"
        if [[ "${PREVIOUS_TIMER_STATE}" != active ]]; then
          WORKSPACE_STATE="代码和数据库未更新；原应用已恢复并通过健康检查，备份定时器保持操作前的停止状态。"
        fi
      else
        WORKSPACE_STATE="代码和数据库未更新，但服务恢复未通过检查；请执行 status 和 logs 排查。"
      fi
    else
      stop_for_maintenance || true
      WORKSPACE_STATE="已尝试停止应用和备份定时器；代码或数据库可能已变更，请先执行 status 确认。"
      WORKSPACE_ADVICE="不要重复更新或迁移；按 docs/UBUNTU_DEPLOYMENT.md 的版本感知回滚步骤处理。"
    fi
  fi
  [[ -z "${RECOVERY_SNAPSHOT}" ]] || printf '回滚快照：%s\n' "${RECOVERY_SNAPSHOT}" | workspace_error_details
}

workspace_cleanup() {
  # Failed post-maintenance updates keep their runtime rollback directory.
  if [[ "${DATA_MAY_HAVE_CHANGED}" == false && -n "${frontend_stage_dir:-}" ]]; then
    cleanup_frontend_stage || true
  fi
  if [[ -n "${offline_stage:-}" && "${offline_stage}" == /var/lib/solution-workspace-releases/update.* \
    && -d "${offline_stage}" && ! -L "${offline_stage}" ]]; then
    rm -rf -- "${offline_stage}"
  fi
}

