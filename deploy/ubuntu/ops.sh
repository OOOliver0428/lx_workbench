    ;;
  update)
    remote=origin
    branch=main
    offline_input=""
    expected_commit=""
    offline_stage=""
    if [[ "${1:-}" == --offline ]]; then
      [[ "$#" -ge 2 && -n "$2" && "$2" != --* ]] || fail "用法：update --offline /路径/更新包.bundle [--branch 分支名]" E_ARGUMENT
      offline_input="$2"
      branch=""
      shift 2
      if [[ "$#" -gt 0 ]]; then
